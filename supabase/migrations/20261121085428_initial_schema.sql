-- ===== Members (allowlist + roles) =====
create table public.members (
  email text primary key check (email = lower(btrim(email)) and email like '%_@_%'),
  role text not null check (role in ('owner','admin','viewer')),
  user_id uuid unique references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index members_one_owner on public.members ((true)) where role = 'owner';

-- ===== Data tables: one JSON document per row, same shape the app already uses =====
create table public.players (
  id bigint generated by default as identity primary key,
  data jsonb not null default '{}'::jsonb,
  version integer not null default 1,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid()
);
create table public.nights (like public.players including all);
create table public.chips  (like public.players including all);
-- "like ... including all" copies the identity; give each table its own sequence
alter table public.nights alter column id drop identity;
alter table public.nights alter column id add generated by default as identity;
alter table public.chips alter column id drop identity;
alter table public.chips alter column id add generated by default as identity;

-- version bump on every update (used to detect two admins editing at once)
create function public.bump_version() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.version := old.version + 1;
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end $$;
create trigger players_bump before update on public.players for each row execute function public.bump_version();
create trigger nights_bump  before update on public.nights  for each row execute function public.bump_version();
create trigger chips_bump   before update on public.chips   for each row execute function public.bump_version();

-- ===== Role helpers =====
create function public.app_role() returns text
language sql stable security definer set search_path = '' as $$
  select role from public.members where user_id = auth.uid()
$$;

-- editor = owner/admin who signed in with the authenticator code (aal2)
create function public.is_editor() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select role in ('owner','admin') from public.members where user_id = auth.uid()), false)
     and coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
$$;

-- ===== RLS =====
alter table public.members enable row level security;
alter table public.players enable row level security;
alter table public.nights  enable row level security;
alter table public.chips   enable row level security;

do $$
declare t text;
begin
  foreach t in array array['players','nights','chips'] loop
    execute format('create policy "members read" on public.%I for select to authenticated using (public.app_role() is not null)', t);
    execute format('create policy "editors insert" on public.%I for insert to authenticated with check (public.is_editor())', t);
    execute format('create policy "editors update" on public.%I for update to authenticated using (public.is_editor()) with check (public.is_editor())', t);
    execute format('create policy "editors delete" on public.%I for delete to authenticated using (public.is_editor())', t);
  end loop;
end $$;

create policy "see self" on public.members for select to authenticated using (user_id = auth.uid());
create policy "editors see all" on public.members for select to authenticated using (public.is_editor());
create policy "editors add" on public.members for insert to authenticated
  with check (public.is_editor() and role in ('admin','viewer') and user_id is null);
create policy "editors change" on public.members for update to authenticated
  using (public.is_editor() and role <> 'owner')
  with check (public.is_editor() and role in ('admin','viewer'));
create policy "editors remove" on public.members for delete to authenticated
  using (public.is_editor() and role <> 'owner');

-- members may only change role, or clear user_id (reset login) — never set it to someone
create function public.members_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if current_user in ('authenticated','anon') then
    if tg_op = 'UPDATE' then
      if new.email <> old.email then raise exception 'Email cannot be changed'; end if;
      if new.user_id is not null and new.user_id is distinct from old.user_id then
        raise exception 'Not allowed';
      end if;
    end if;
  end if;
  return new;
end $$;
create trigger members_guard before update on public.members for each row execute function public.members_guard();

