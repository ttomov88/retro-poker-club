-- ===== Accounts can only be created for listed emails =====
create function public.only_listed_signups() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.email_confirmed_at is null
     or not exists (select 1 from public.members m where m.email = lower(new.email) and m.user_id is null) then
    raise exception 'This email is not invited to Retro Poker Club';
  end if;
  return new;
end $$;
create trigger only_listed_signups before insert on auth.users for each row execute function public.only_listed_signups();

-- Used by the claim function (service role only): clears any old account for a listed, unclaimed email
create function public.claim_prepare(p_email text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.members where email = lower(btrim(p_email)) and user_id is null) then
    return false;
  end if;
  delete from auth.users where lower(email) = lower(btrim(p_email));
  return true;
end $$;
revoke execute on function public.claim_prepare(text) from anon, authenticated, public;
grant execute on function public.claim_prepare(text) to service_role;

-- ===== Full restore from a backup file (atomic) =====
create function public.import_all(payload jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare t text; r jsonb;
begin
  if not public.is_editor() then raise exception 'Only admins can import'; end if;
  delete from public.nights; delete from public.players; delete from public.chips;
  foreach t in array array['players','nights','chips'] loop
    for r in select * from jsonb_array_elements(coalesce(payload -> t, '[]'::jsonb)) loop
      if jsonb_typeof(r) <> 'object' or jsonb_typeof(r -> 'id') <> 'number' then
        raise exception 'The backup has damaged % records. Nothing was changed.', t;
      end if;
      execute format('insert into public.%I (id, data) values ($1, $2)', t)
        using (r ->> 'id')::bigint, (r - 'id' - '_v');
    end loop;
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
                   'public.' || t, t);
  end loop;
end $$;
revoke execute on function public.import_all(jsonb) from anon, public;
grant execute on function public.import_all(jsonb) to authenticated;

